func insertSourceChunks(ctx context.Context, tx *sql.Tx, sourceID, body, hash string) error {
	chunks, err := BuildSourceChunks(sourceID, body, hash, DefaultChunkSize, DefaultChunkOverlap)
	if err != nil {
		return err
	}
	for _, chunk := range chunks {
		if _, err := tx.ExecContext(ctx, `
			INSERT IGNORE INTO wiki_chunks (id, source_id, content_hash, start_offset, end_offset)
			VALUES (?, ?, ?, ?, ?)
		`, chunk.ID, sourceID, hash, chunk.Start, chunk.End); err != nil {
			return err
		}
	}
	return nil
}

// sourceChunks uses persisted IDs for evidence. Some legacy sources already
// have chunks whose IDs differ from the IDs generated by the Go writer.
func (s *Store) sourceChunks(ctx context.Context, job *JobRecord, sources []SourceRecord) (map[string][]Chunk, error) {
	chunks, err := loadSourceChunks(ctx, s.DB, sources)
	if err != nil {
		return nil, err
	}
	var missing []SourceRecord
	for _, source := range sources {
		if source.Verified && source.Body != "" && len(chunks[source.ID]) == 0 {
			missing = append(missing, source)
		}
	}
	if len(missing) == 0 {
		return chunks, nil
	}

	err = s.WithTx(ctx, func(tx *sql.Tx) error {
		var channelID string
		if err := tx.QueryRowContext(ctx, "SELECT id FROM wiki_channels WHERE id=? FOR UPDATE", job.ChannelID).Scan(&channelID); err != nil {
			return err
		}
		if err := s.FenceJob(ctx, tx, job); err != nil {
			return err
		}
		repaired, err := loadSourceChunks(ctx, tx, missing)
		if err != nil {
			return err
		}
		for _, source := range missing {
			if len(repaired[source.ID]) > 0 {
				chunks[source.ID] = repaired[source.ID]
				continue
			}
			var hash string
			err := tx.QueryRowContext(ctx, `
				SELECT content_hash FROM wiki_sources
				WHERE id=? AND channel_id=? AND verified AND NOT deleted AND NOT hidden AND NOT excluded
				FOR UPDATE
			`, source.ID, channelID).Scan(&hash)
			if errors.Is(err, sql.ErrNoRows) {
				continue
			}
			if err != nil {
				return err
			}
			if hash != source.ContentHash {
				continue
			}
			if err := insertSourceChunks(ctx, tx, source.ID, source.Body, hash); err != nil {
				return err
			}
		}
		repaired, err = loadSourceChunks(ctx, tx, missing)
		if err != nil {
			return err
		}
		for id, parts := range repaired {
			chunks[id] = parts
		}
		return nil
	})
	if err != nil {
		return nil, fmt.Errorf("prepare missing Wiki source chunks: %w", err)
	}
	return chunks, nil
}

func loadSourceChunks(ctx context.Context, exec sqlExecutor, sources []SourceRecord) (map[string][]Chunk, error) {
	out := make(map[string][]Chunk)
	ids := make([]string, 0, len(sources))
	byID := make(map[string]SourceRecord, len(sources))
	for _, source := range sources {
		if source.Verified && source.Body != "" {
			ids = append(ids, source.ID)
			byID[source.ID] = source
		}
	}
	if len(ids) == 0 {
		return out, nil
	}
	placeholders, args := stringPlaceholders(ids)
	rows, err := exec.QueryContext(ctx, `
		SELECT c.id,c.source_id,c.content_hash,c.start_offset,c.end_offset
		FROM wiki_chunks c JOIN wiki_sources s ON s.id=c.source_id AND s.content_hash=c.content_hash
		WHERE c.source_id IN (`+placeholders+`)
		  AND s.verified AND NOT s.deleted AND NOT s.hidden AND NOT s.excluded
		ORDER BY c.source_id,c.start_offset,c.end_offset,c.id
	`, args...)
	if err != nil {
		return nil, fmt.Errorf("load stored Wiki source chunks: %w", err)
	}
	defer func() { _ = rows.Close() }()
	var prevID string
	var runes []rune
	for rows.Next() {
		var chunk Chunk
		if err := rows.Scan(&chunk.ID, &chunk.SourceID, &chunk.ContentHash, &chunk.Start, &chunk.End); err != nil {
			return nil, err
		}
		source := byID[chunk.SourceID]
		if source.ContentHash != chunk.ContentHash {
			continue
		}
		if prevID != chunk.SourceID {
			runes = []rune(source.Body)
			prevID = chunk.SourceID
		}
		if chunk.Start < 0 || chunk.Start >= chunk.End || chunk.End > len(runes) {
			return nil, fmt.Errorf("invalid stored offsets for Wiki chunk %s", chunk.ID)
		}
		chunk.Text = string(runes[chunk.Start:chunk.End])
		out[chunk.SourceID] = append(out[chunk.SourceID], chunk)
	}
	return out, rows.Err()
}
